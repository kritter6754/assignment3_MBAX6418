"""The song library: bundled sample songs plus songs generated while the app runs.

Each song is a folder holding meta.json, an audio file and a cover image:
  assets/samples/<id>/   ready-to-play samples shipped with the app (read-only)
  <DATA_DIR>/tracks/<id>/ songs generated by users (git-ignored)
"""
from __future__ import annotations

import io
import json
import shutil
import threading
import time
from pathlib import Path

from PIL import Image

from .config import SAMPLES_DIR
from .creative import normalize_lyrics


def save_cover(raw: bytes, dest_dir: Path, max_side: int = 768) -> str:
    """Store a cover as a reasonably small JPEG; returns its file name."""
    with Image.open(io.BytesIO(raw)) as im:
        im = im.convert("RGB")
        im.thumbnail((max_side, max_side))
        im.save(dest_dir / "cover.jpg", "JPEG", quality=88)
    return "cover.jpg"


class Library:
    def __init__(self, data_dir: Path, samples_dir: Path = SAMPLES_DIR):
        self.samples_dir = samples_dir
        self.tracks_dir = data_dir / "tracks"
        self.tracks_dir.mkdir(parents=True, exist_ok=True)
        self._lock = threading.Lock()
        self._tracks: dict[str, dict] = {}
        self._remove_unfinished()
        self._load(samples_dir, "sample")
        self._load(self.tracks_dir, "generated")

    def _remove_unfinished(self) -> None:
        """Delete folders of songs that never finished (the app stopped mid-generation).
        Runs at startup, when no generation can be in progress."""
        for folder in self.tracks_dir.iterdir():
            if folder.is_dir() and not (folder / "meta.json").is_file():
                shutil.rmtree(folder, ignore_errors=True)

    def _load(self, root: Path, source: str) -> None:
        if not root.is_dir():
            return
        for meta_path in sorted(root.glob("*/meta.json")):
            meta = json.loads(meta_path.read_text())
            folder = meta_path.parent
            if not (folder / meta.get("audio", "")).is_file():
                continue  # an interrupted generation; ignore it
            meta.update(id=folder.name, source=source)
            self._tracks[folder.name] = meta

    def folder(self, track: dict) -> Path:
        return (self.samples_dir if track["source"] == "sample" else self.tracks_dir) / track["id"]

    def list(self) -> list[dict]:
        with self._lock:
            tracks = list(self._tracks.values())
        # samples first (in their numbered order), then newest generated songs first
        samples = sorted((t for t in tracks if t["source"] == "sample"), key=lambda t: t["id"])
        generated = sorted((t for t in tracks if t["source"] != "sample"),
                           key=lambda t: t.get("created_at", 0), reverse=True)
        return samples + generated

    def get(self, track_id: str) -> dict | None:
        with self._lock:
            return self._tracks.get(track_id)

    def add(self, track_id: str, meta: dict) -> dict:
        folder = self.tracks_dir / track_id
        meta = {**meta, "created_at": meta.get("created_at", time.time())}
        (folder / "meta.json").write_text(json.dumps(meta, indent=2, ensure_ascii=False))
        meta.update(id=track_id, source="generated")
        with self._lock:
            self._tracks[track_id] = meta
        return meta

    @staticmethod
    def public(track: dict) -> dict:
        """The fields the browser needs, with media URLs."""
        base = f"/media/{'samples' if track['source'] == 'sample' else 'tracks'}/{track['id']}"
        keys = ("id", "title", "style", "mood", "duration_s", "vocal", "language", "theme",
                "summary", "lyrics", "source", "created_at")
        out = {k: track.get(k) for k in keys}
        out["lyrics"] = normalize_lyrics(out.get("lyrics") or "")  # also repairs songs saved before the fix
        out["audio_url"] = f"{base}/{track['audio']}"
        out["cover_url"] = f"{base}/{track['cover']}" if track.get("cover") else None
        return out
